import { fetchDoc } from './fetch.js';
import { flattenNodes, jsonLdBlocks, typesOf, firstOffer, hrefs, visibleText, decodeEntities } from './html.js';

export const AI_AGENTS = [
  'GPTBot',
  'OAI-SearchBot',
  'ClaudeBot',
  'PerplexityBot',
  'Google-Extended',
  'Applebot-Extended',
];

export function normalizeDomain(input) {
  return String(input || '')
    .trim()
    .toLowerCase()
    .replace(/^https?:\/\//, '')
    .replace(/\/.*$/, '')
    .replace(/^www\./, '');
}

export function detectPlatform(headers, html) {
  const h = headers || {};
  if (h['x-shopid'] || h['x-shopify-stage'] || /cdn\.shopify\.com|Shopify\.theme|myshopify\.com/.test(html)) return 'Shopify';
  if (/woocommerce/i.test(html)) return 'WooCommerce';
  if (/bigcommerce/i.test(html)) return 'BigCommerce';
  if (/wixstatic|wix\.com/i.test(html)) return 'Wix';
  if (/squarespace/i.test(html)) return 'Squarespace';
  if (/salesforce commerce|demandware/i.test(html)) return 'Salesforce CC';
  return 'Custom/Unknown';
}

function parseRobots(text) {
  const groups = [];
  let cur = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*/, '').trim();
    if (!line) continue;
    const m = line.match(/^([A-Za-z-]+)\s*:\s*(.*)$/);
    if (!m) continue;
    const field = m[1].toLowerCase();
    const value = m[2].trim();
    if (field === 'user-agent') {
      if (!cur || cur.rules.length > 0) {
        cur = { agents: [], rules: [] };
        groups.push(cur);
      }
      cur.agents.push(value.toLowerCase());
    } else if (field === 'allow' || field === 'disallow') {
      if (!cur) {
        cur = { agents: ['*'], rules: [] };
        groups.push(cur);
      }
      cur.rules.push({ type: field, path: value });
    }
  }
  return groups;
}

function isAllowed(groups, agentLower) {
  const rules = [];
  for (const g of groups) {
    if (g.agents.includes(agentLower) || g.agents.includes('*')) {
      for (const r of g.rules) rules.push(r);
    }
  }
  const effective = rules.filter((r) => r.path !== '');
  if (effective.length === 0) return { allowed: true, rule: null };
  const matches = effective.filter((r) => r.path === '/' || '/'.startsWith(r.path) || r.path === '/*');
  const candidates = matches.length ? matches : [];
  if (!candidates.length) return { allowed: true, rule: null };
  candidates.sort((a, b) => b.path.length - a.path.length);
  const top = candidates[0];
  return { allowed: top.type === 'allow', rule: top };
}

async function checkRobots(origin) {
  const max = 20;
  const res = await fetchDoc(`${origin}/robots.txt`, { timeoutMs: 10000 });
  if (res.status === 404) {
    return {
      id: 'robots-ai',
      label: 'AI crawler access',
      max,
      earned: max,
      note: 'No robots.txt — nothing is blocked.',
      evidence: { agents: AI_AGENTS.map((a) => ({ agent: a, allowed: true, rule: null })) },
    };
  }
  if (!res.ok) {
    return {
      id: 'robots-ai',
      label: 'AI crawler access',
      max,
      earned: Math.round(max / 2),
      note: `robots.txt returned ${res.error || res.status}; treated as default-open.`,
      evidence: {},
    };
  }
  const groups = parseRobots(res.body);
  const rows = AI_AGENTS.map((agent) => {
    const { allowed, rule } = isAllowed(groups, agent.toLowerCase());
    return { agent, allowed, rule: rule ? `${rule.type}: ${rule.path}` : null };
  });
  const allowedCount = rows.filter((r) => r.allowed).length;
  const blocked = rows.filter((r) => !r.allowed).map((r) => r.agent);
  return {
    id: 'robots-ai',
    label: 'AI crawler access',
    max,
    earned: Math.round((allowedCount / rows.length) * max),
    note: blocked.length ? `Blocked: ${blocked.join(', ')}` : 'All major AI agents allowed.',
    evidence: { agents: rows },
  };
}

async function checkLlms(origin) {
  const max = 10;
  const res = await fetchDoc(`${origin}/llms.txt`, { timeoutMs: 10000 });
  if (res.ok && res.body.trim().length > 40) {
    const hasHeading = /^#\s+\S/m.test(res.body);
    const agentRails = /\b(UCP|Universal Commerce Protocol|WebMCP|agentic checkout|Shop skill)\b/i.test(res.body);
    const autoGenerated = /Agent Instructions —/.test(res.body) && agentRails;
    const note = autoGenerated
      ? 'Auto-generated agent purchase guide (platform default).'
      : hasHeading
        ? 'Custom llms.txt present and structured.'
        : 'llms.txt present, missing a top-level heading.';
    return {
      id: 'llms-txt',
      label: 'llms.txt',
      max,
      earned: hasHeading ? max : Math.round(max * 0.5),
      note,
      evidence: { agentRails, autoGenerated, preview: res.body.slice(0, 400) },
    };
  }
  return { id: 'llms-txt', label: 'llms.txt', max, earned: 0, note: 'No /llms.txt.', evidence: { agentRails: false } };
}

function checkHomeSchema(html) {
  const max = 15;
  const nodes = flattenNodes(jsonLdBlocks(html));
  const types = new Set(nodes.flatMap(typesOf));
  const has = (...t) => t.some((x) => types.has(x));
  let earned = 0;
  const found = [];
  if (has('Organization', 'LocalBusiness', 'OnlineStore', 'Store')) {
    earned += 8;
    found.push('Organization');
  }
  if (has('WebSite')) {
    earned += 4;
    found.push('WebSite');
  }
  if (has('BreadcrumbList', 'ItemList', 'SearchAction', 'SiteNavigationElement')) {
    earned += 3;
    found.push('Navigation');
  }
  return {
    id: 'home-schema',
    label: 'Entity markup (home)',
    max,
    earned,
    note: found.length ? `Found: ${found.join(', ')}` : 'No Organization or WebSite JSON-LD.',
    evidence: { types: [...types].slice(0, 24) },
  };
}

async function checkProductSchema(productUrl) {
  const max = 20;
  if (!productUrl) {
    return { id: 'product-schema', label: 'Product markup', max, earned: 0, note: 'No crawlable product page found.', evidence: {} };
  }
  const res = await fetchDoc(productUrl, { timeoutMs: 14000 });
  if (!res.ok) {
    return {
      id: 'product-schema',
      label: 'Product markup',
      max,
      earned: 0,
      note: `Product page returned ${res.error || res.status}.`,
      evidence: { productUrl },
    };
  }
  const nodes = flattenNodes(jsonLdBlocks(res.body));
  const product = nodes.find((n) => typesOf(n).includes('Product'));
  if (!product) {
    return {
      id: 'product-schema',
      label: 'Product markup',
      max,
      earned: 0,
      note: 'No Product JSON-LD on the product page.',
      evidence: { productUrl },
    };
  }
  const offer = firstOffer(product);
  const fields = [
    ['name', Boolean(product.name), 4],
    ['price', Boolean(offer && (offer.price != null || offer.lowPrice != null)), 4],
    ['currency', Boolean(offer && offer.priceCurrency), 4],
    ['availability', Boolean(offer && offer.availability), 4],
    ['image', Boolean(product.image), 2],
    ['sku/gtin', Boolean(product.sku || product.gtin || product.gtin13 || product.mpn), 2],
  ];
  const earned = fields.reduce((sum, [, ok, weight]) => sum + (ok ? weight : 0), 0);
  const missing = fields.filter(([, ok]) => !ok).map(([name]) => name);
  return {
    id: 'product-schema',
    label: 'Product markup',
    max,
    earned,
    note: missing.length ? `Missing: ${missing.join(', ')}` : 'Complete core product fields.',
    evidence: {
      productUrl,
      present: fields.filter(([, ok]) => ok).map(([name]) => name),
      missing,
    },
  };
}

async function checkCatalog(origin) {
  const max = 15;
  let earned = 0;
  const evidence = {};
  const pj = await fetchDoc(`${origin}/products.json?limit=1`, { timeoutMs: 10000 });
  if (pj.ok) {
    try {
      const parsed = JSON.parse(pj.body);
      if (Array.isArray(parsed.products)) {
        earned += 8;
        evidence.productsJson = 'ok';
        if (parsed.products[0] && parsed.products[0].handle) {
          evidence.firstProductHandle = parsed.products[0].handle;
        }
      }
    } catch {
      // Non-JSON body at a Shopify-shaped endpoint; ignore.
    }
  }
  const sm = await fetchDoc(`${origin}/sitemap.xml`, { timeoutMs: 10000 });
  if (sm.ok && /<urlset|<sitemapindex/i.test(sm.body)) {
    earned += 4;
    evidence.sitemap = 'ok';
  }
  const sp = await fetchDoc(`${origin}/sitemap_products_1.xml`, { timeoutMs: 10000 });
  if (sp.ok && /<urlset/i.test(sp.body)) {
    earned += 3;
    evidence.productSitemap = 'ok';
  }
  const keys = ['productsJson', 'sitemap', 'productSitemap'].filter((k) => evidence[k]);
  return {
    id: 'catalog',
    label: 'Machine-readable catalog',
    max,
    earned,
    note: keys.length ? `Feeds: ${keys.join(', ')}` : 'No public catalog feed or sitemap.',
    evidence,
  };
}

function checkPolicies(origin, html) {
  const max = 10;
  const links = hrefs(html, origin).filter((u) => {
    try {
      return new URL(u).origin === origin;
    } catch {
      return false;
    }
  });
  const wanted = [
    ['shipping', /shipping|delivery/i],
    ['returns', /return|refund|exchange/i],
    ['contact', /contact|support|help/i],
    ['privacy', /privacy/i],
  ];
  const found = [];
  const urls = {};
  for (const [name, re] of wanted) {
    const hit = links.find((u) => re.test(u));
    if (hit) {
      found.push(name);
      urls[name] = hit;
    }
  }
  return {
    id: 'policies',
    label: 'Agent-legible policies',
    max,
    earned: Math.round((found.length / wanted.length) * max),
    note: found.length ? `Linked: ${found.join(', ')}` : 'No shipping, returns, contact, or privacy links in home markup.',
    evidence: { found, urls },
  };
}

function checkServerRendered(html) {
  const max = 10;
  const chars = visibleText(html).length;
  const earned = chars >= 2000 ? 10 : chars >= 900 ? 7 : chars >= 300 ? 4 : chars > 0 ? 2 : 0;
  return {
    id: 'server-rendered',
    label: 'Server-rendered content',
    max,
    earned,
    note: `${chars} visible characters in raw HTML.`,
    evidence: { chars },
  };
}

function findProductLink(html, origin) {
  const candidate = hrefs(html, origin).find((u) => /\/(products?|item|shop|p)\//i.test(u));
  return candidate || null;
}

function extractMeta(html) {
  const title = (html.match(/<title[^>]*>([\s\S]*?)<\/title>/i) || [null, ''])[1];
  const descMatch =
    html.match(/<meta[^>]+name=["']description["'][^>]+content=["']([^"']*)["']/i) ||
    html.match(/<meta[^>]+content=["']([^"']*)["'][^>]+name=["']description["']/i);
  const nodes = flattenNodes(jsonLdBlocks(html));
  const org = nodes.find((n) =>
    typesOf(n).some((t) => ['Organization', 'LocalBusiness', 'OnlineStore', 'Store'].includes(t)),
  );
  return {
    title: decodeEntities(title).slice(0, 200),
    description: decodeEntities(descMatch ? descMatch[1] : '').slice(0, 400),
    orgName: org && typeof org.name === 'string' ? org.name : null,
    logo: org && typeof org.logo === 'string' ? org.logo : null,
    sameAs: org && Array.isArray(org.sameAs) ? org.sameAs.filter((s) => typeof s === 'string').slice(0, 10) : [],
  };
}

export async function scanDomain(rawDomain) {
  const domain = normalizeDomain(rawDomain);
  const home = await fetchDoc(`https://${domain}/`, { timeoutMs: 15000 });
  let origin = `https://${domain}`;
  if (home.url) {
    try {
      origin = new URL(home.url).origin;
    } catch {
      // Keep the constructed origin.
    }
  }
  const html = home.body || '';
  const base = {
    domain,
    origin,
    status: home.status,
    ok: home.ok,
    error: home.error,
    platform: detectPlatform(home.headers, html),
    meta: extractMeta(html),
    scannedAt: new Date().toISOString(),
  };

  if (!home.ok) {
    const botWall = home.status === 401 || home.status === 403 || home.status === 429;
    return {
      ...base,
      blocked: botWall,
      score: null,
      grade: botWall ? 'N/A' : 'F',
      checks: [
        {
          id: 'reachable',
          label: botWall ? 'Automated access blocked' : 'Reachable',
          max: 100,
          earned: 0,
          note: botWall
            ? `HTTP ${home.status} to a plain automated request — a bot wall agents will also hit.`
            : home.error || `Homepage returned ${home.status}.`,
          evidence: {},
        },
      ],
    };
  }

  const [robots, llms, catalog] = await Promise.all([checkRobots(origin), checkLlms(origin), checkCatalog(origin)]);
  const productUrl =
    catalog.evidence.firstProductHandle
      ? `${origin}/products/${catalog.evidence.firstProductHandle}`
      : findProductLink(html, origin);
  const productSchema = await checkProductSchema(productUrl);

  const checks = [
    robots,
    llms,
    checkHomeSchema(html),
    productSchema,
    catalog,
    checkPolicies(origin, html),
    checkServerRendered(html),
  ];

  const max = checks.reduce((s, c) => s + c.max, 0) || 100;
  const raw = checks.reduce((s, c) => s + c.earned, 0);
  const score = Math.round((raw / max) * 100);

  return { ...base, score, grade: gradeOf(score), checks };
}

export function gradeOf(score) {
  if (score >= 85) return 'A';
  if (score >= 70) return 'B';
  if (score >= 55) return 'C';
  if (score >= 40) return 'D';
  return 'F';
}

export function gaps(record) {
  return [...record.checks]
    .filter((c) => c.earned < c.max)
    .sort((a, b) => b.max - b.earned - (a.max - a.earned));
}
